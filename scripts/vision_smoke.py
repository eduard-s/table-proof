"""Run the real pinned model on a declared synthetic PDF. No mocked inference."""

from __future__ import annotations

import argparse
import json
import platform
from collections import Counter
from importlib.metadata import version
from pathlib import Path
from time import perf_counter

from reportlab.pdfgen.canvas import Canvas

from table_proof.models import BBox, Cell, Table
from table_proof.vision import VisionConfig, compare_structure, detect_structure


def make_example(path: Path) -> Table:
    values = [
        ["Sample", "Mass (g)", "Volume (mL)", "Density (g/mL)"],
        ["Alpha", "12.4", "10.0", "1.24"],
        ["Beta", "24.6", "20.0", "1.23"],
        ["Gamma", "36.9", "30.0", "1.23"],
        ["Delta", "49.2", "40.0", "1.23"],
    ]
    canvas = Canvas(str(path), pagesize=(612, 792))
    canvas.setTitle("TableProof synthetic vision smoke example")
    canvas.setFont("Helvetica-Bold", 15)
    canvas.drawString(72, 735, "Synthetic laboratory measurements")
    canvas.setFont("Helvetica", 9)
    canvas.drawString(72, 716, "Demonstration values. No experimental or scientific claim.")
    x0, top, width, row_height = 72.0, 100.0, 468.0, 36.0
    cells = []
    for r, row in enumerate(values):
        for c, text in enumerate(row):
            left = x0 + c * width / 4
            cell_top = top + r * row_height
            canvas.setFillColorRGB(0.9, 0.93, 0.96) if r == 0 else canvas.setFillColorRGB(1, 1, 1)
            canvas.rect(left, 792 - cell_top - row_height, width / 4, row_height, fill=1, stroke=1)
            canvas.setFillColorRGB(0, 0, 0)
            canvas.setFont("Helvetica-Bold" if r == 0 else "Helvetica", 10)
            canvas.drawString(left + 8, 792 - cell_top - 23, text)
            cells.append(
                Cell(
                    id=f"r{r}c{c}",
                    row=r,
                    col=c,
                    text=text,
                    column_header=r == 0,
                    bbox=BBox(
                        x0=left, top=cell_top, x1=left + width / 4, bottom=cell_top + row_height
                    ),
                )
            )
    canvas.save()
    return Table(
        id="synthetic-lab",
        page=1,
        num_rows=5,
        num_cols=4,
        cells=cells,
        bbox=BBox(x0=x0, top=top, x1=x0 + width, bottom=top + row_height * 5),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("/tmp/table-proof-vision-smoke"))
    parser.add_argument("--allow-download", action="store_true")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    source = args.output / "synthetic-source.pdf"
    table = make_example(source)
    config = VisionConfig(allow_download=args.allow_download)
    start = perf_counter()
    result = detect_structure(source, table, config=config)
    total = perf_counter() - start
    clean = compare_structure(table, result, config=config)
    cells = list(table.cells)
    cells[6] = cells[6].model_copy(update={"col": 1})
    mutated = compare_structure(table.model_copy(update={"cells": cells}), result, config=config)
    report = {
        "data": "synthetic PDF generated by scripts/vision_smoke.py; not a quality benchmark",
        "model_id": result.model_id,
        "model_revision": result.model_revision,
        "device": "cpu",
        "python": platform.python_version(),
        "platform": platform.platform(),
        "versions": {
            name: version(name) for name in ("torch", "transformers", "timm", "pdfplumber")
        },
        "image_size": [result.image_width, result.image_height],
        "crop_pdf_points": result.crop_bbox.model_dump(),
        "inference_seconds": result.inference_seconds,
        "total_seconds_including_load": total,
        "region_counts": dict(
            Counter(r.label for r in result.regions if r.score >= config.score_threshold)
        ),
        "regions": [
            {"label": r.label, "score": r.score, "bbox": r.bbox.model_dump()}
            for r in result.regions
        ],
        "clean_findings": [finding.model_dump() for finding in clean],
        "mutated_findings": [finding.model_dump() for finding in mutated],
    }
    (args.output / "result.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({k: v for k, v in report.items() if k != "regions"}, indent=2))
    return 0 if any(f.code == "vision_cell_relation_mismatch" for f in mutated) else 1


if __name__ == "__main__":
    raise SystemExit(main())
